#!/usr/bin/env bash
set -euo pipefail

repo=/shared/data/home/aa3242/physics
python="$repo/model_evals/gemini/.venv/bin/python"
key_file=${OPENROUTER_KEY_FILE:-/shared/data/home/aa3242/.config/openrouter/api_key}
base_url=https://openrouter.ai/api/v1

if [[ ! -s "$key_file" ]]; then
    echo "Missing OpenRouter key file: $key_file" >&2
    exit 2
fi

export OPENROUTER_API_KEY
OPENROUTER_API_KEY=$(<"$key_file")
export OPENROUTER_PROVIDER_SORT=throughput
export OPENROUTER_APP_TITLE="Physics LLM Evaluation"
cd "$repo"
mkdir -p \
    model_evals/kimi/runs/kimi-k3-max-no-tools-20260917/{hle-corrected,native-original} \
    model_evals/glm/runs/glm-5.3-max-no-tools-20260917/{hle-corrected,native-original} \
    model_evals/deepseek/runs/deepseek-v4-pro-max-no-tools-20260917/{hle-corrected,native-original}

record_kimi_transition() {
    "$python" - <<'PY'
import json
from datetime import datetime, timezone
from pathlib import Path

root = Path("model_evals/kimi/runs/kimi-k3-max-no-tools-20260917/hle-corrected")
counts = {"prism": 74, "ugphysics": 78, "hle": 115, "cmt": 49, "critpt": 54}
attempts = {}
for benchmark, count in counts.items():
    for attempt in range(1, 5):
        path = root / benchmark / f"attempt-{attempt}" / "predictions.json"
        rows = json.loads(path.read_text()) if path.exists() else {}
        dataset = json.loads((root / benchmark / f"attempt-{attempt}" / "dataset.json").read_text())
        ids = [str(row["id"]) for row in dataset]
        attempts[f"{benchmark}/attempt-{attempt}"] = {
            "local_prediction_ids": [qid for qid in ids if qid in rows],
            "openrouter_pending_ids": [qid for qid in ids if qid not in rows],
            "expected_count": count,
        }
report = {
    "created_at": datetime.now(timezone.utc).isoformat(),
    "conceptual_model": "moonshotai/Kimi-K3",
    "original_route": "local vLLM on mi355-gpu-35",
    "resume_route": "https://openrouter.ai/api/v1 / moonshotai/kimi-k3",
    "provider_sort": "throughput",
    "reason": "User-requested transition from local GPU inference to OpenRouter",
    "attempts": attempts,
}
temporary = root / "provider-transition.json.tmp"
temporary.write_text(json.dumps(report, indent=2) + "\n")
temporary.replace(root / "provider-transition.json")
PY
}

archive_empty_kimi_native_preparation() {
    local native="$repo/model_evals/kimi/runs/kimi-k3-max-no-tools-20260917/native-original/kimi"
    local archive="$repo/model_evals/kimi/runs/kimi-k3-max-no-tools-20260917/native-original/pre-openrouter-prepared"
    mkdir -p "$archive"
    for benchmark in phybench prism ugphysics; do
        local source="$native/$benchmark/attempt-1"
        local target="$archive/${benchmark}-attempt-1"
        [[ -d "$source" ]] || continue
        "$python" - "$source" <<'PY'
import json
import sys
from pathlib import Path

path = Path(sys.argv[1]) / "predictions.json"
if path.exists() and json.loads(path.read_text()):
    raise SystemExit(f"Refusing to archive nonempty predictions: {path}")
PY
        [[ ! -e "$target" ]] || { echo "Archive already exists: $target" >&2; return 1; }
        mv "$source" "$target"
    done
}

run_corrected() {
    local model_key=$1 served_model=$2 generation_workers=$3
    "$python" -u model_evals/open_models/run_corrected_hle.py \
        --model "$model_key" --base-url "$base_url" --served-model "$served_model" \
        --generation-workers "$generation_workers" --judge-workers 10 \
        --parallel 24 --retries 8 --transport-timeout 10800 --stage all
}

run_original() {
    local model_key=$1 served_model=$2 generation_workers=$3
    "$python" -u model_evals/open_models/run_original_native.py \
        --model "$model_key" --base-url "$base_url" --served-model "$served_model" \
        --generation-workers "$generation_workers" --retries 8 \
        --transport-timeout 10800 --stage all
}

# Resume Kimi corrected in place. Stable manifest overrides preserve the
# existing local checkpoints; provider-transition.json records the exact IDs
# generated by each route.
record_kimi_transition
"$python" -u model_evals/open_models/run_corrected_hle.py \
    --model kimi-k3 --base-url "$base_url" --served-model moonshotai/kimi-k3 \
    --manifest-base-url http://127.0.0.1:8000/v1 --manifest-model moonshotai/Kimi-K3 \
    --generation-workers 16 --judge-workers 10 --parallel 20 --retries 8 \
    --transport-timeout 10800 --stage all \
    >>model_evals/kimi/runs/kimi-k3-max-no-tools-20260917/hle-corrected/openrouter-supervisor.log 2>&1

archive_empty_kimi_native_preparation
run_original kimi moonshotai/kimi-k3 24 \
    >>model_evals/kimi/runs/kimi-k3-max-no-tools-20260917/native-original/openrouter-supervisor.log 2>&1

run_corrected glm-5.3 z-ai/glm-5.3 16 \
    >>model_evals/glm/runs/glm-5.3-max-no-tools-20260917/hle-corrected/openrouter-supervisor.log 2>&1
run_original glm z-ai/glm-5.3 24 \
    >>model_evals/glm/runs/glm-5.3-max-no-tools-20260917/native-original/openrouter-supervisor.log 2>&1

run_corrected deepseek-v4-pro deepseek/deepseek-v4-pro 24 \
    >>model_evals/deepseek/runs/deepseek-v4-pro-max-no-tools-20260917/hle-corrected/openrouter-supervisor.log 2>&1
run_original deepseek deepseek/deepseek-v4-pro 42 \
    >>model_evals/deepseek/runs/deepseek-v4-pro-max-no-tools-20260917/native-original/openrouter-supervisor.log 2>&1

date -Is >model_evals/open_models/openrouter-sequence-complete.txt
